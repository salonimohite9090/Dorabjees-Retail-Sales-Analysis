-- query 9 revenue by store and product category
-- for each store how much revenue is generated by each product category

SELECT
    st.store_name,
    p.category,
    SUM(s.sales_amount) AS total_revenue
FROM sales AS s
JOIN stores AS st   ON s.store_id   = st.store_id
JOIN products AS p  ON s.product_id = p.product_id
GROUP BY st.store_name, p.category
ORDER BY st.store_name, total_revenue DESC;

-- query 10 average order value by customer type
-- what is the average amount spent in a transaction by each type of customer

SELECT
    c.customer_type,
    ROUND(AVG(s.sales_amount), 2) AS avg_order_value
FROM sales AS s
JOIN customers AS c 
ON s.customer_id = c.customer_id
GROUP BY c.customer_type;

-- 11 top 5 customers by total spending
-- have spent the most in Dorabjess

SELECT
    c.customer_name,
    SUM(s.sales_amount) AS total_spent
FROM sales AS s
JOIN customers AS c ON s.customer_id = c.customer_id
GROUP BY c.customer_name
ORDER BY total_spent DESC
LIMIT 5;

-- 12 top 5 products by profit 

