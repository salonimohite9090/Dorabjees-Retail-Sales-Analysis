-- query 5 store perfprmance and revenue ranking 
-- used subquery,joins,rank,group by
SELECT
    sub.store_id,
    sub.store_name,
    sub.total_revenue,
    sub.total_profit,
    sub.total_transactions,
    sub.avg_order_value,
    RANK() OVER (ORDER BY sub.total_transactions DESC) AS revenue_rank -- rank according to profit and total revenue  changes
FROM 
(
    SELECT 
        s.store_id,
        st.store_name,
        SUM(s.sales_amount)   AS total_revenue,
        SUM(s.profit)         AS total_profit,
        COUNT(*)              AS total_transactions,
        AVG(s.sales_amount)   AS avg_order_value
    FROM sales AS s
    JOIN stores AS st
        ON s.store_id = st.store_id
    GROUP BY s.store_id, st.store_name
) 
AS sub;

